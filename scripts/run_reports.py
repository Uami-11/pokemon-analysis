"""Phase 7 - execute the SQL reports and render them to Markdown.

Reads `sql/reports.sql`, splits it on `-- @report:` markers, runs each query
against PostgreSQL and writes `reports/sql_reports.md` with the SQL plus a
Markdown table of the result.

    python scripts/run_reports.py
"""

from __future__ import annotations

import os
import re
import sys
from datetime import datetime
from pathlib import Path

import pandas as pd
from sqlalchemy import create_engine, text

ROOT = Path(__file__).resolve().parents[1]
REPORTS_SQL = ROOT / "sql" / "reports.sql"
OUT = ROOT / "reports" / "sql_reports.md"

DEFAULT_URL = "postgresql+psycopg2:///pokemon_analysis"
MARKER = re.compile(r"^--\s*@report:\s*(?P<title>.+?)\s*$", re.MULTILINE)
MAX_ROWS = 50


def split_reports(sql_text: str) -> list[tuple[str, str]]:
    matches = list(MARKER.finditer(sql_text))
    reports = []
    for i, m in enumerate(matches):
        start = m.end()
        end = matches[i + 1].start() if i + 1 < len(matches) else len(sql_text)
        body = sql_text[start:end].strip()
        body = body.rstrip().rstrip(";").strip()
        if body:
            reports.append((m.group("title"), body))
    return reports


def md_escape(value) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "NULL"
    s = str(value)
    return s.replace("|", "\\|")


def to_markdown(df: pd.DataFrame) -> str:
    truncated = len(df) > MAX_ROWS
    shown = df.head(MAX_ROWS)
    header = "| " + " | ".join(md_escape(c) for c in shown.columns) + " |"
    sep = "| " + " | ".join("---" for _ in shown.columns) + " |"
    rows = ["| " + " | ".join(md_escape(v) for v in rec) + " |"
            for rec in shown.itertuples(index=False, name=None)]
    out = "\n".join([header, sep, *rows])
    if truncated:
        out += f"\n\n_({len(df)} rows total, showing first {MAX_ROWS})_"
    return out


def main() -> int:
    url = os.environ.get("POKEMON_DB_URL", DEFAULT_URL)
    engine = create_engine(url)
    reports = split_reports(REPORTS_SQL.read_text())

    parts = [
        "# SQL reports\n",
        f"Generated: {datetime.now():%Y-%m-%d %H:%M}  ",
        f"Database: `{engine.url.database}` (schema `pokemon`)  ",
        f"Reports: {len(reports)}\n",
        "Auto-generated by `scripts/run_reports.py` from `sql/reports.sql`.\n",
    ]

    ok = True
    with engine.connect() as conn:
        for title, body in reports:
            try:
                df = pd.read_sql(text(body), conn)
            except Exception as exc:  # noqa: BLE001
                ok = False
                print(f"  [FAIL] {title}: {exc}")
                parts.append(f"## {title}\n\n**Error:** {exc}\n")
                continue
            print(f"  [ok] {title}  -> {len(df)} rows x {len(df.columns)} cols")
            parts.append(
                f"## {title}\n\n"
                f"```sql\n{body}\n```\n\n"
                f"{to_markdown(df)}\n"
            )

    OUT.write_text("\n".join(parts))
    print(f"\nwrote {OUT.relative_to(ROOT)} ({len(reports)} reports)")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
